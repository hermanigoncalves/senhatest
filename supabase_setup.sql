-- 1. Criação da Tabela Principal de Senhas (tickets)
CREATE TABLE IF NOT EXISTS public.tickets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  call_id INT NOT NULL DEFAULT 1,
  number VARCHAR(20) NOT NULL,
  raw_number INT NOT NULL,
  desk VARCHAR(50) NOT NULL,
  type VARCHAR(20) DEFAULT 'Normal',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Índices de Desempenho para Respostas Instantâneas da TV
CREATE INDEX IF NOT EXISTS idx_tickets_id_desc ON public.tickets (id DESC);
CREATE INDEX IF NOT EXISTS idx_tickets_call_id ON public.tickets (call_id DESC);
CREATE INDEX IF NOT EXISTS idx_tickets_raw_number ON public.tickets (raw_number);

-- 3. Habilitar RLS (Row Level Security) e Criar Políticas Permissivas
ALTER TABLE public.tickets ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Permitir Leitura Pública de Senhas" ON public.tickets;
DROP POLICY IF EXISTS "Permitir Inserção Pública de Senhas" ON public.tickets;
DROP POLICY IF EXISTS "Permitir Atualização de Senhas" ON public.tickets;
DROP POLICY IF EXISTS "Permitir Exclusão de Senhas" ON public.tickets;

CREATE POLICY "Permitir Leitura Pública de Senhas" 
ON public.tickets FOR SELECT 
USING (true);

CREATE POLICY "Permitir Inserção Pública de Senhas" 
ON public.tickets FOR INSERT 
WITH CHECK (true);

CREATE POLICY "Permitir Atualização de Senhas" 
ON public.tickets FOR UPDATE 
USING (true);

CREATE POLICY "Permitir Exclusão de Senhas" 
ON public.tickets FOR DELETE 
USING (true);

-- 4. Função SQL para Zerar a Fila de Forma Atômica e Rápida
CREATE OR REPLACE FUNCTION public.reset_cmip_queue()
RETURNS void AS $$
BEGIN
  TRUNCATE TABLE public.tickets RESTART IDENTITY;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 5. Função SQL para Definir Senha Inicial e Limpar Senhas Conflitantes no Banco
CREATE OR REPLACE FUNCTION public.set_initial_ticket_cmip(target_num INT)
RETURNS void AS $$
BEGIN
  IF target_num <= 1 THEN
    TRUNCATE TABLE public.tickets RESTART IDENTITY;
  ELSE
    DELETE FROM public.tickets WHERE raw_number >= target_num;
  END IF;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 6. Função de Limpeza Automática de Senhas Antigas (Opcional - Limpa senhas com mais de 7 dias)
CREATE OR REPLACE FUNCTION public.clean_old_tickets()
RETURNS void AS $$
BEGIN
  DELETE FROM public.tickets WHERE created_at < NOW() - INTERVAL '7 days';
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;
