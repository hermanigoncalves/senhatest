CREATE TABLE public.appointments (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  patient_id BIGINT REFERENCES public.patients(id) ON DELETE SET NULL,
  name VARCHAR(150),
  phone VARCHAR(30) NOT NULL,
  professional_id BIGINT REFERENCES public.doctors(id) ON DELETE SET NULL,
  doctor_name VARCHAR(150),
  service VARCHAR(100) DEFAULT 'Consulta de Rotina',
  appointment_date DATE NOT NULL,
  appointment_time VARCHAR(10) NOT NULL,
  scheduled_at TIMESTAMPTZ,
  duration_minutes INT NOT NULL DEFAULT 30,
  room_number VARCHAR(10) NOT NULL DEFAULT '1',
  status VARCHAR(30) NOT NULL DEFAULT 'AGENDADO'
      CHECK (status IN ('pending', 'AGENDADO', 'CHECKIN', 'CHAMADO', 'EM_ATENDIMENTO', 'FINALIZADO', 'CANCELADO', 'FALTOU')),
  insurance_type VARCHAR(50) DEFAULT 'PARTICULAR',
  price DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Trigger para sincronizar data/hora e auto-vincular paciente
CREATE OR REPLACE FUNCTION sync_appointment_fields()
RETURNS TRIGGER AS $$
BEGIN
  NEW.scheduled_at := (NEW.appointment_date || ' ' || NEW.appointment_time || ':00')::TIMESTAMP;
  IF NEW.patient_id IS NULL AND NEW.phone IS NOT NULL THEN
    SELECT id INTO NEW.patient_id FROM public.patients WHERE phone = NEW.phone LIMIT 1;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_sync_appointment
BEFORE INSERT OR UPDATE ON public.appointments
FOR EACH ROW EXECUTE FUNCTION sync_appointment_fields();

